def main():
    with io.open("video.json", encoding="utf-8") as f:
        plan = json.load(f)

    assert len(plan["scenes"]) == 63, len(plan["scenes"])
    changed = 0
    for sc in plan["scenes"]:
        n = sc["id"]
        assert n in NEW, "no new narration for scene %d" % n
        if sc["narration"] != NEW[n]:
            changed += 1
        sc["narration"] = NEW[n]

    plan["history"].append({
        "stage": "scriptwriter + language-editor",
        "note": ("timing pass: voice-02 clips measured 10.8-13.9s raw vs 10.0s slot "
                 "(voice_filter trims to slot after atempo<=1.15 -> tails were being cut). "
                 "Rewrote all 63 narrations to <=20 words and <=3 dramatic pauses "
                 "(target raw <=11.0s). Arc, facts, hook/CTA and footage_query kept identical."),
    })

    with io.open("video.json", "w", encoding="utf-8") as f:
        json.dump(plan, f, ensure_ascii=False, indent=1)
        f.write("\n")
    print("patched %d scenes (%d changed)" % (len(plan["scenes"]), changed))


if __name__ == "__main__":
    main()
